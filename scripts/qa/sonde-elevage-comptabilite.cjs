/** Serveur et base locaux obligatoires ; fixtures de essai-elevage-comptabilite.ts. */
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { createRequire } = require('node:module')
const { chromium } = createRequire('/var/www/escalier/package.json')('playwright')
const { PrismaClient } = require('@prisma/client')

async function main() {
  const base = 'http://127.0.0.1:3012'
  const fixture = JSON.parse(await fs.readFile('/tmp/gleba-reglements-fixture.json', 'utf8'))
  const env = await fs.readFile('/tmp/gleba-reglements-qa.env', 'utf8')
  const url = env.split('\n').find((l) => l.startsWith('DATABASE_URL=')).slice('DATABASE_URL='.length)
  assert.match(new URL(url).pathname, /^\/gleba_reglements_qa_[a-z0-9_]+$/)
  const db = new PrismaClient({ datasources: { db: { url } } })
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'fr-FR', timezoneId: 'Europe/Paris' })
  const page = await context.newPage()
  page.setDefaultTimeout(30000); page.setDefaultNavigationTimeout(120000)
  const erreurs = []; page.on('pageerror', (e) => erreurs.push(String(e)))
  const connexion = async (ctx, email) => {
    const csrf = await (await ctx.request.get(`${base}/api/auth/csrf`)).json()
    const r = await ctx.request.post(`${base}/api/auth/callback/credentials`, { form: { csrfToken: csrf.csrfToken, email, password: fixture.password, callbackUrl: `${base}/elevage`, json: 'true' }, headers: { 'X-Auth-Return-Redirect': '1' } })
    assert.equal(r.status(), 200); assert(!((await r.json()).url || '').includes('error='))
  }
  const api = async (path, data, method = 'GET', status = 200, ctx = context) => {
    const r = await ctx.request.fetch(`${base}${path}`, { method, ...(data === undefined ? {} : { data }), timeout: 120000 })
    const j = await r.json(); assert.equal(r.status(), status, `${method} ${path}: ${JSON.stringify(j)}`); return j.data ?? j
  }
  const venteDb = (id) => db.venteProduit.findUniqueOrThrow({ where: { id } })
  const miroirDb = (id) => db.venteManuelle.findFirstOrThrow({ where: { userId: fixture.userId, sourceType: 'vente_produit', sourceId: id } })
  const ventesAvant = await db.venteProduit.count({ where: { userId: fixture.userId } })
  try {
    await connexion(context, fixture.email)
    const oeufs = await api('/api/elevage/ventes', { date: fixture.date, type: 'oeufs', description: 'Œufs QA parcours', quantite: 2, unite: 'douzaine', prixUnitaire: 3, paye: false, modeReglement: 'Chèque' }, 'POST', 201)
    let miroir = await miroirDb(oeufs.id)
    assert.equal(miroir.paye, false); assert.equal(miroir.modeReglement, 'Chèque')
    assert.equal((await db.mouvementStockOeuf.aggregate({ where: { userId: fixture.userId, notes: { startsWith: `[vente-produit:${oeufs.id}]` } }, _sum: { quantite: true } }))._sum.quantite, 24)
    const autre = await browser.newContext(); await connexion(autre, fixture.autreEmail)
    await api('/api/comptabilite/ventes-manuelles', { id: miroir.id, paye: true }, 'PATCH', 404, autre)
    const lecteur = await browser.newContext(); await connexion(lecteur, fixture.lecteurEmail)
    await api('/api/comptabilite/ventes-manuelles', { id: miroir.id, paye: true }, 'PATCH', 403, lecteur)
    await autre.close(); await lecteur.close()
    await page.goto(`${base}/comptabilite/transactions`, { waitUntil: 'networkidle' })
    const cookies = page.getByRole('button', { name: 'Tout refuser', exact: true }); if (await cookies.isVisible()) await cookies.click()
    const ligne = page.getByRole('row').filter({ hasText: 'Œufs QA parcours' })
    await ligne.getByText('À encaisser', { exact: true }).waitFor(); await ligne.getByText('Chèque', { exact: true }).waitFor()
    await ligne.getByRole('button', { name: 'Règlement et pièce', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Règlement et pièce', exact: true })
    assert.equal(await dialog.getByLabel('Encaissement confirmé', { exact: true }).isChecked(), false)
    await dialog.getByLabel('Mode de règlement', { exact: true }).selectOption('Virement')
    await dialog.getByLabel('Encaissement confirmé', { exact: true }).check()
    const enregistre = page.waitForResponse((r) => r.url().endsWith('/api/comptabilite/ventes-manuelles') && r.request().method() === 'PATCH')
    await dialog.getByRole('button', { name: 'Enregistrer', exact: true }).click(); assert.equal((await enregistre).status(), 200)
    assert.equal((await venteDb(oeufs.id)).paye, true)
    await ligne.getByText('Encaissé', { exact: true }).waitFor(); await ligne.getByText('Virement', { exact: true }).waitFor()
    await fs.mkdir('/tmp/gleba-reglements-captures', { recursive: true })
    await page.screenshot({ path: '/tmp/gleba-reglements-captures/transactions-bureau.png', fullPage: true })
    const nouvelEtat = await api('/api/elevage/ventes?annee=all'); assert.equal(nouvelEtat.find((v) => v.id === oeufs.id).modeReglement, 'Virement')
    await api('/api/elevage/ventes', { id: oeufs.id, quantite: 3 }, 'PATCH')
    miroir = await miroirDb(oeufs.id); assert.equal(miroir.modeReglement, 'Virement'); assert.equal(miroir.paye, true)
    const nbAvantRefus = await db.venteProduit.count({ where: { userId: fixture.userId } })
    await api('/api/elevage/ventes', { date: fixture.date, type: 'oeufs', quantite: 1000, unite: 'douzaine', prixUnitaire: 3, paye: false }, 'POST', 409)
    assert.equal(await db.venteProduit.count({ where: { userId: fixture.userId } }), nbAvantRefus, 'stock insuffisant : aucune vente ni recette fantôme')
    const sortie = await db.mouvementStockOeuf.findFirstOrThrow({ where: { userId: fixture.userId, notes: { startsWith: `[vente-produit:${oeufs.id}]` } } })
    await api(`/api/elevage/stock-oeufs?id=${sortie.id}`, undefined, 'DELETE', 409)
    await api('/api/comptabilite/ventes-manuelles', { id: miroir.id, paye: false }, 'PATCH')
    const factureSource = await api('/api/elevage/ventes', { id: oeufs.id, creerFacture: true }, 'PATCH')
    const facture = await db.facture.findUniqueOrThrow({ where: { id: factureSource.factureId } })
    assert.equal(facture.statut, 'emise'); assert.equal(facture.modePaiement, 'virement'); assert.equal(facture.totalTTC, 9)
    assert.equal(await db.venteManuelle.count({ where: { userId: fixture.userId, sourceType: 'vente_produit', sourceId: oeufs.id } }), 0)
    await api('/api/comptabilite/factures', { id: facture.id, statut: 'payee' }, 'PATCH')
    assert.equal((await venteDb(oeufs.id)).paye, true)
    await api('/api/comptabilite/factures', { id: facture.id, statut: 'emise' }, 'PATCH')
    assert.equal((await venteDb(oeufs.id)).paye, false)
    await api('/api/elevage/ventes', { id: oeufs.id, prixUnitaire: 4 }, 'PATCH', 409)
    await api('/api/elevage/ventes', { id: oeufs.id, paye: true }, 'PATCH', 409)
    assert.equal((await venteDb(oeufs.id)).prixTotal, 9)
    await api(`/api/elevage/ventes?id=${oeufs.id}`, undefined, 'DELETE')
    assert.equal((await venteDb(oeufs.id)).annule, true)
    assert.equal((await db.facture.findUniqueOrThrow({ where: { id: facture.id } })).statut, 'annulee')
    assert.equal(await db.mouvementStockOeuf.count({ where: { userId: fixture.userId, notes: { startsWith: `[vente-produit:${oeufs.id}]` } } }), 0)
    const fromage = await api('/api/elevage/ventes', { date: fixture.date, type: 'fromage', quantite: 1, unite: 'pièce', prixUnitaire: 6, paye: true, modeReglement: 'CB', lotFromageId: fixture.fromageId }, 'POST', 201)
    const mouvementFromage = await db.mouvementFromage.findFirstOrThrow({ where: { venteProduitId: fromage.id } })
    await api(`/api/elevage/mouvements-fromage?id=${mouvementFromage.id}`, undefined, 'DELETE', 409)
    await api(`/api/elevage/ventes?id=${fromage.id}`, undefined, 'DELETE')
    assert.equal(await db.mouvementFromage.count({ where: { venteProduitId: fromage.id } }), 0)
    const miel = await api('/api/elevage/ventes', { date: fixture.date, type: 'miel', quantite: 1, unite: 'kg', prixUnitaire: 12, paye: true, modeReglement: 'Espèces' }, 'POST', 201)
    const sortieMiel = await db.mouvementStockRuche.findFirstOrThrow({ where: { venteProduitId: miel.id } })
    await api(`/api/elevage/stock-ruche?operationId=${sortieMiel.operationId}`, undefined, 'DELETE', 409)
    await api(`/api/elevage/ventes?id=${miel.id}`, undefined, 'DELETE')
    assert.equal(await db.mouvementStockRuche.count({ where: { venteProduitId: miel.id } }), 0)
    await api('/api/elevage/lots', { id: fixture.lotId, nom: 'Pondeuses QA corrigées' }, 'PATCH')
    const achats = await api('/api/comptabilite/depenses')
    const achat = achats.find((d) => d.source === 'LotAnimaux' && d.sourceId === fixture.lotId)
    assert.equal(achat.paye, false); assert.equal(achat.ecriture.suivi.numeroPiece, 'ACH-QA'); assert.equal(achat.modeReglement, 'Virement')
    const fec = await api('/api/comptabilite/export/fec?check=1'); assert.equal(fec.validation.equilibre, true)
    await page.goto(`${base}/elevage?tab=production&sub=ventes`, { waitUntil: 'networkidle' })
    await page.getByRole('button', { name: /Nouvelle vente/ }).click()
    const nouveau = page.getByRole('dialog')
    assert.equal(await nouveau.getByLabel('Encaissement confirmé', { exact: true }).isChecked(), false)
    assert.equal(await nouveau.getByLabel('Mode de règlement', { exact: true }).inputValue(), '')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: '/tmp/gleba-reglements-captures/vente-mobile.png', fullPage: true })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await nouveau.getByRole('button', { name: 'Annuler', exact: true }).click()
    assert.deepEqual(erreurs, [])
    assert.equal(await db.venteProduit.count({ where: { userId: fixture.userId, annule: false } }), ventesAvant)
    console.log('Parcours navigateur : mode et encaissement, propagation aux deux écrans, régénération, stock, refus de survente, facture unique, dépointage, annulations œufs/fromage/miel, achats, FEC, droits et mobile validés.')
  } finally { await context.close(); await browser.close(); await db.$disconnect() }
}
main().catch((e) => { console.error(e); process.exitCode = 1 })
