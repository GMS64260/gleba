/* Parcours navigateur sur le banc local uniquement ; aucune donnée de production. */
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { createRequire } = require('node:module')
const localRequire = createRequire(`${process.env.PLAYWRIGHT_DIR || '/var/www/escalier'}/package.json`)
const { chromium } = localRequire('playwright')

async function main() {
  const base = process.env.GLEBA_COMMERCIAL_QA_URL || 'http://127.0.0.1:3007'
  if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw new Error('Cette sonde exige un banc local isolé')
  const clientId = process.env.GLEBA_COMMERCIAL_QA_CLIENT_ID
  if (!clientId || !process.env.GLEBA_COMMERCIAL_QA_PASSWORD) throw new Error('Fiche client et mot de passe de contrôle requis')
  const dossier = process.env.GLEBA_COMMERCIAL_QA_ARTIFACTS || '/tmp/gleba-devis-qa'
  await fs.mkdir(dossier, { recursive: true })
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 1346, height: 950 }, extraHTTPHeaders: { 'x-forwarded-for': '203.0.113.71' } })
  const page = await context.newPage()
  const erreurs = []
  page.on('pageerror', (e) => erreurs.push(String(e)))
  const connexion = async (ctx, email) => {
    const csrf = await (await ctx.request.get(`${base}/api/auth/csrf`)).json()
    const r = await ctx.request.post(`${base}/api/auth/callback/credentials`, { form: { csrfToken: csrf.csrfToken, email, password: process.env.GLEBA_COMMERCIAL_QA_PASSWORD, callbackUrl: `${base}/comptabilite/factures?tab=devis`, json: 'true' }, headers: { 'X-Auth-Return-Redirect': '1' } })
    assert.equal(r.status(), 200)
    assert(!((await r.json()).url || '').includes('error='), 'connexion de contrôle')
  }
  try {
    await connexion(context, 'demo@gleba.fr')
    await page.goto(`${base}/comptabilite/factures?tab=devis`, { waitUntil: 'networkidle' })
    const cookies = page.getByRole('button', { name: 'Tout refuser', exact: true })
    if (await cookies.isVisible()) await cookies.click()
    await page.getByRole('button', { name: 'Nouveau devis', exact: true }).click()
    await page.locator('#doc-client').selectOption(clientId)
    await page.locator('#doc-objet').fill('Commande de légumes · contrôle navigateur')
    await page.getByLabel('Désignation *', { exact: true }).fill('Carottes de contrôle')
    await page.getByLabel('Quantité *', { exact: true }).fill('10')
    await page.getByLabel('Prix unitaire HT *', { exact: true }).fill('2')
    await page.locator('#doc-notes').fill('Paiement à réception. Livraison convenue à la ferme.')
    const sauvegarde = page.waitForResponse((r) => r.url().endsWith('/api/comptabilite/documents') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Enregistrer le brouillon', exact: true }).click()
    const sr = await sauvegarde; assert.equal(sr.status(), 201)
    const devis = (await sr.json()).data
    const ligne = page.locator(`#document-${devis.id}`)
    await ligne.waitFor()
    await page.screenshot({ path: `${dossier}/devis-bureau.png`, fullPage: true })
    await page.setViewportSize({ width: 375, height: 900 })
    await page.screenshot({ path: `${dossier}/devis-mobile.png`, fullPage: true })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'aucun débordement horizontal à 375 px')
    await page.setViewportSize({ width: 1346, height: 950 })
    const transition = async (texte) => {
      await ligne.getByRole('button', { name: texte, exact: true }).click()
      const attente = page.waitForResponse((r) => r.url().endsWith(`/documents/${devis.id}`) && r.request().method() === 'PATCH')
      await page.getByRole('button', { name: 'Confirmer', exact: true }).click()
      const r = await attente; assert.equal(r.status(), 200); return (await r.json()).data
    }
    const emis = await transition('Émettre')
    await ligne.getByText('Émis', { exact: true }).waitFor()
    const resultats = await (await context.request.get(`${base}/api/search?q=${encodeURIComponent(emis.numero)}`)).json()
    assert(resultats.items.some((i) => i.id === `document-${devis.id}` && i.href.includes(`document=${devis.id}`)), 'devis retrouvable par la recherche globale')
    await transition('Enregistrer l’accord')
    await ligne.getByText('Accepté', { exact: true }).waitFor()
    const pdf = await context.request.get(`${base}/api/comptabilite/documents/${devis.id}/pdf`)
    assert.equal(pdf.status(), 200); assert((await pdf.body()).subarray(0, 4).equals(Buffer.from('%PDF')))
    await ligne.getByRole('button', { name: 'Envoyer', exact: true }).click()
    await page.getByText(/courriels y sont désactivés/).waitFor()
    assert(await page.getByRole('button', { name: 'Envoyer le PDF par courriel', exact: true }).isDisabled())
    await page.keyboard.press('Escape')
    const bonReponse = page.waitForResponse((r) => r.url().endsWith(`/documents/${devis.id}/livraison`) && r.request().method() === 'POST')
    await ligne.getByRole('button', { name: 'Créer le bon de livraison', exact: true }).click()
    const br = await bonReponse; assert.equal(br.status(), 201)
    await page.waitForURL(/tab=livraisons/)
    // La conversion recharge la page ; le corps de l'ancienne réponse peut déjà avoir été libéré par Chromium.
    const bons = await (await context.request.get(`${base}/api/comptabilite/documents?type=livraison&annee=all`)).json()
    const bon = bons.data.find((d) => d.devisOrigineId === devis.id)
    assert(bon, 'le bon créé reste lié au devis après navigation')
    const livraison = page.locator(`#document-${bon.id}`)
    await livraison.getByRole('button', { name: 'Marquer livré', exact: true }).click()
    const livree = page.waitForResponse((r) => r.url().endsWith(`/documents/${bon.id}`) && r.request().method() === 'PATCH')
    await page.getByRole('button', { name: 'Confirmer la livraison', exact: true }).click()
    assert.equal((await livree).status(), 200)
    await livraison.getByRole('button', { name: 'Facturer ce bon', exact: true }).click()
    const factureReponse = page.waitForResponse((r) => r.url().endsWith('/documents/facturer') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Confirmer et générer la facture', exact: true }).click()
    const fr = await factureReponse; assert.equal(fr.status(), 201)
    const facture = (await fr.json()).data
    assert.equal(facture.totalTTC, 21.1)
    await page.getByRole('cell', { name: facture.numero, exact: true }).waitFor()
    await page.screenshot({ path: `${dossier}/facture-bureau.png`, fullPage: true })
    const refus = await context.request.post(`${base}/api/comptabilite/envois`, { data: { type: 'facture', id: String(facture.id), cle: require('node:crypto').randomUUID(), destinataire: 'client@example.test', message: '' } })
    assert.equal(refus.status(), 403, 'aucun courriel réel depuis la démo')
    const etranger = await browser.newContext({ extraHTTPHeaders: { 'x-forwarded-for': '203.0.113.72' } })
    await connexion(etranger, 'autre-commercial@example.test')
    assert.equal((await etranger.request.get(`${base}/api/comptabilite/documents/${devis.id}/pdf`)).status(), 404)
    const rechercheEtrangere = await (await etranger.request.get(`${base}/api/search?q=${encodeURIComponent(emis.numero)}`)).json()
    assert(!rechercheEtrangere.items.some((i) => i.id === `document-${devis.id}`))
    assert.equal((await etranger.request.post(`${base}/api/comptabilite/documents/facturer`, { data: { ids: [bon.id], dateEcheance: '2099-12-31' } })).status(), 404)
    await etranger.close()
    const lecteur = await browser.newContext({ extraHTTPHeaders: { 'x-forwarded-for': '203.0.113.73' } })
    await connexion(lecteur, 'lecture-commercial@example.test')
    assert.equal((await lecteur.request.get(`${base}/api/comptabilite/documents/${devis.id}/pdf`)).status(), 200, 'lecture partagée')
    assert.equal((await lecteur.request.patch(`${base}/api/comptabilite/documents/${devis.id}`, { data: { action: 'annuler' } })).status(), 403, 'consultation sans écriture')
    await lecteur.close()
    await page.goto(`${base}/comptabilite/factures?tab=devis&document=${devis.id}`, { waitUntil: 'networkidle' })
    await page.locator(`#document-${devis.id}`).getByText('Facturé', { exact: true }).waitFor()
    assert.deepEqual(erreurs, [], 'aucune erreur JavaScript')
    console.log(JSON.stringify({ ok: true, devis: emis.numero, bon: bon.numero, facture: facture.numero, mobile: true, isolation: true, consultation: true, envoiDemoBloque: true, artefacts: dossier }))
  } catch (e) {
    await page.screenshot({ path: `${dossier}/echec-navigateur.png`, fullPage: true })
    throw e
  } finally { await browser.close() }
}
main().catch((e) => { console.error(e); process.exitCode = 1 })
